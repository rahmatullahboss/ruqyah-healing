export function getDemoCourseContentRows() {
  const courses = demoCourses.map(({ modules: _modules, ...course }) => course);
  const modules = demoCourses.flatMap((course) => course.modules.map(({ lessons: _lessons, quizzes: _quizzes = [], ...module }) => ({
    ...module,
    courseId: course.id,
  })));
  const lessons = demoCourses.flatMap((course) => course.modules.flatMap((module) => module.lessons.map((lesson) => ({
    ...lesson,
    moduleId: module.id,
    courseId: course.id,
    videoUrl: lesson.videoUrl || '',
    videoProvider: lesson.videoProvider || 'youtube',
    resources: lesson.resources || [],
    allowResourceDownload: Boolean(lesson.allowResourceDownload),
  }))));
  const quizzes = demoCourses.flatMap((course) => course.modules.flatMap((module) => (module.quizzes || []).map(({ questions: _questions, ...quiz }) => ({
    ...quiz,
    moduleId: module.id,
    courseId: course.id,
  }))));
  const quizQuestions = demoCourses.flatMap((course) => course.modules.flatMap((module) => (module.quizzes || []).flatMap((quiz) => quiz.questions.map((question) => ({
    ...question,
    quizId: quiz.id,
  })))));

  return { courses, modules, lessons, quizzes, quizQuestions };
}
